import { ReactNode } from "react";

export type Language = "java" | "sql" | "cpp";

const words = (s: string) => new Set(s.split(" "));

const KEYWORDS: Record<Language, Set<string>> = {
  java: words(
    "abstract boolean break case catch char class continue default do double else enum extends final finally float for if " +
      "implements import instanceof int interface long new null package private protected public record return short static " +
      "super switch synchronized this throw throws true false try var void while yield",
  ),
  sql: words(
    "CREATE TABLE ALTER ADD COLUMN INDEX ON PRIMARY KEY NOT NULL DEFAULT REFERENCES UNIQUE BIGINT INT VARCHAR TEXT BOOLEAN " +
      "NUMERIC TIMESTAMP WITH TIME ZONE GENERATED BY AS IDENTITY DATE",
  ),
  cpp: words(
    "auto bool break case catch char class const constexpr continue default delete do double else enum explicit false float " +
      "for friend if inline int long namespace new noexcept nullptr operator private protected public return short signed " +
      "sizeof static static_cast struct switch template this throw true try typename using virtual void while std size_t",
  ),
};

const TOKEN = /("""[\s\S]*?"""|"(?:\\.|[^"\\\n])*"|'(?:\\.|[^'\\\n])*'|@\w+|#\w+|\b\d[\d_.]*[LlDdFf]?\b|\b[A-Za-z_]\w*\b|\s+|.)/g;

export function languageOf(file: string): Language {
  if (file.endsWith(".sql")) return "sql";
  if (/\.(cpp|h|hpp)$/.test(file)) return "cpp";
  return "java";
}

function highlight(code: string, lang: Language): ReactNode[] {
  const out: ReactNode[] = [];
  const keywords = KEYWORDS[lang];
  let key = 0;
  for (const match of code.matchAll(TOKEN)) {
    const t = match[0];
    let cls = "";
    if (t.startsWith('"') || t.startsWith("'")) cls = "tok-string";
    else if (t.startsWith("@") || (lang === "cpp" && t.startsWith("#"))) cls = "tok-annotation";
    else if (/^\d/.test(t)) cls = "tok-number";
    else if (lang === "sql" ? keywords.has(t.toUpperCase()) && t === t.toUpperCase() : keywords.has(t)) cls = "tok-keyword";
    else if (lang !== "sql" && /^[A-Z][a-zA-Z0-9]*$/.test(t)) cls = "tok-type";
    out.push(cls ? <span key={key++} className={cls}>{t}</span> : t);
  }
  return out;
}

export default function CodeBlock({ code, startLine = 1, lang = "java", maxHeight }: {
  code: string;
  startLine?: number;
  lang?: Language;
  maxHeight?: string;
}) {
  const lines = code.split("\n");
  return (
    <div className="code-block overflow-auto rounded-lg text-[12.5px] leading-[1.6]" style={{ maxHeight }}>
      <pre className="flex min-w-max py-3 font-mono">
        <span aria-hidden className="select-none border-r border-white/10 px-3 text-right tok-gutter">
          {lines.map((_, i) => <div key={i}>{startLine + i}</div>)}
        </span>
        <code className="px-4">{highlight(code, lang)}</code>
      </pre>
    </div>
  );
}
